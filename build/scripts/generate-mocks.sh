#!/bin/sh
# Generate Go mock implementations with mockgen (go.uber.org/mock).
#
# This script is the single entry point for regenerating all committed mockgen.go
# files in the repository. Run it after adding or changing interfaces that tests
# depend on, then commit the updated mockgen.go artifacts.
#
# Usage (from repo root):
#   sh build/scripts/generate-mocks.sh
#
# Output:
#   One mockgen.go per package listed at the bottom of this script. Generated
#   files should be committed to source control; CI runs `make generated-check` to
#   ensure they stay in sync.
#
#   Mockgen receives a full import path and interface
#     names, compiles the package, and reflects over types. Works for interfaces
#     in this module and in dependencies.
#
# Unexported interfaces and mock naming:
#   Go interfaces whose names start with a lowercase letter are package-private.
#   Tests in the same package can mock them, but mockgen's default naming is ugly:
#
#     interface:  configApplier
#     default:    MockconfigApplier / NewMockconfigApplier
#                         ^ lowercase letter after "Mock" looks wrong
#
#   We pass gomock's -mock_names flag to rename only the mock TYPE, keeping the
#   mock unexported and capitalizing the interface-name portion:
#
#     interface:  configApplier
#     mock type:  mockConfigApplier        (unexported — not part of public API)
#     constructor NewmockConfigApplier     (mockgen always prefixes "New" + type name)
#
#   Exported interfaces (RestoreManager, ClientFactory, ...) keep mockgen defaults:
#
#     interface:  RestoreManager
#     mock type:  MockRestoreManager
#     constructor NewMockRestoreManager
#
#   The build_mock_names helper below builds the -mock_names string automatically
#   for every lowercase interface in a generate_mocks call. No post-processing.
#
# Adding a new mock:
#   1. Define the interface in the target package (exported or unexported).
#   2. Append the interface name to the appropriate generate_mocks call below.
#   3. Run this script and commit the updated mockgen.go.
#   4. In tests (same package as the interface), construct mocks with the generated constructor.
#
# Dependency interfaces (e.g. backup-go) are generated with generate_external_mocks into a
# separate *mockgen.go file so they do not overwrite the package's own mockgen.go.

set -e

# Ensure mockgen is available. Pin is intentionally loose (@latest) so local dev and
# CI pick up a compatible generator; generated output is checked into git anyway.
if ! command -v mockgen > /dev/null 2>&1; then
    go install go.uber.org/mock/mockgen@latest
fi

# Always run from the repository root so relative -destination paths in mockgen's
# "Generated by this command" header are identical on every machine (local vs CI).
WORKSPACE="$(git rev-parse --show-toplevel)"
echo "Workspace root: $WORKSPACE"
cd "$WORKSPACE"

# Full module import path, e.g. github.com/aerospike/aerospike-backup-service/v3
# Used to build the package argument passed to mockgen in reflect mode.
BASE_IMPORT_PATH=$(grep '^module' "$WORKSPACE/go.mod" | awk '{print $2}')
echo "Module path: $BASE_IMPORT_PATH"

# build_mock_names takes a comma-separated list of interface names and returns a
# comma-separated -mock_names specification for unexported interfaces only.
#
# Example input:  "configApplier,RestoreManager"
# Example output: "configApplier=mockConfigApplier"
#
# Exported interfaces (RestoreManager) are omitted; mockgen defaults apply.
# Returns an empty string when there are no unexported interfaces.
build_mock_names() {
    _interfaces="$1"
    _mock_names=""

    # Split the comma-separated interface list into positional parameters.
    _old_ifs=$IFS
    IFS=','
    # shellcheck disable=SC2086
    set -- $_interfaces
    IFS="$_old_ifs"

    for _iface in "$@"; do
        # In Go, an uppercase first rune means exported; lowercase means package-private.
        _first_char=$(printf '%s' "$_iface" | cut -c1)
        case "$_first_char" in
            [a-z])
                # Capitalize only the first character of the interface name, then prefix "mock".
                # configApplier -> mockConfigApplier
                # storageReaderWriter -> mockStorageReaderWriter
                _cap=$(printf '%s' "$_first_char" | tr '[:lower:]' '[:upper:]')$(printf '%s' "$_iface" | cut -c2-)
                if [ -n "$_mock_names" ]; then
                    _mock_names="$_mock_names,${_iface}=mock${_cap}"
                else
                    _mock_names="${_iface}=mock${_cap}"
                fi
                ;;
        esac
    done

    printf '%s' "$_mock_names"
}

# generate_mocks runs mockgen for one package.
#
# Arguments:
#   $1 - package path relative to repo root (e.g. internal/server/handlers)
#   $2 - comma-separated interface names to mock in that package
#
# Writes: <package>/mockgen.go in the same package as the interfaces so tests can
# use unexported mocks. The output file name is fixed (mockgen.go) to keep imports
# predictable and to match existing repository convention.
generate_mocks() {
    _src_pkg_rel_path="$1"
    _interfaces="$2"

    # mockgen -package must match the source package name (last path segment).
    _out_pkg_name=$(basename "$_src_pkg_rel_path")

    # Relative destination keeps mockgen's self-documenting header stable across machines.
    _dest_rel="$_src_pkg_rel_path/mockgen.go"

    # Reflect-mode import path: module path + relative package path.
    _full_src_pkg_import="$BASE_IMPORT_PATH/$_src_pkg_rel_path"

    echo "--> Generating mocks for $_full_src_pkg_import"
    echo "    Output: $_dest_rel (package $_out_pkg_name)"

    _mock_names=$(build_mock_names "$_interfaces")
    if [ -n "$_mock_names" ]; then
        # At least one unexported interface: pass explicit mock type names.
        echo "    Mock names: $_mock_names"
        mockgen \
            -package "$_out_pkg_name" \
            -destination "$_dest_rel" \
            -mock_names="$_mock_names" \
            "$_full_src_pkg_import" \
            "$_interfaces"
    else
        # All interfaces exported: mockgen defaults (MockFoo / NewMockFoo) are fine.
        mockgen \
            -package "$_out_pkg_name" \
            -destination "$_dest_rel" \
            "$_full_src_pkg_import" \
            "$_interfaces"
    fi

    echo "    Done."
}

# generate_external_mocks runs mockgen for interfaces defined in a dependency.
#
# Arguments:
#   $1 - import path of the source package (e.g. github.com/aerospike/backup-go)
#   $2 - destination package path relative to repo root (e.g. pkg/service/aerospike)
#   $3 - destination file name (e.g. backupgo_mockgen.go) so this does not overwrite mockgen.go
#   $4 - comma-separated interface names to mock
generate_external_mocks() {
    _src_pkg_import="$1"
    _dest_pkg_rel_path="$2"
    _dest_file="$3"
    _interfaces="$4"

    _out_pkg_name=$(basename "$_dest_pkg_rel_path")
    _dest_rel="$_dest_pkg_rel_path/$_dest_file"

    echo "--> Generating mocks for $_src_pkg_import"
    echo "    Output: $_dest_rel (package $_out_pkg_name)"

    mockgen \
        -package "$_out_pkg_name" \
        -destination "$_dest_rel" \
        "$_src_pkg_import" \
        "$_interfaces"

    echo "    Done."
}

generate_mocks \
    "pkg/service" \
    "RestoreManager,BackupReaderWriter,BackupReader,BackupStateRegistry,BackupRetentionManager,ClusterConfigWriter,CancelableBackupHandler,routineProvider,HistoryManager,BackupCompletionHandler,RestoreValidator,StartController,RoutineBackupRunner,NamespaceBackupRunner,BackupReporter,BackupOrchestrator,JobScheduler,storageFileReader,storageDataWriter"

generate_mocks \
    "pkg/service/restoreexecutor" \
    "Restore,RestoreHandler"

generate_mocks \
    "pkg/service/backupexecutor" \
    "Backup,BackupHandler"

generate_mocks \
    "pkg/service/aerospike" \
    "ClientManager,NamespaceResolver,NamespaceValidator,Client,ClientFactory,ClusterConfigSource"

generate_external_mocks \
    "github.com/aerospike/backup-go" \
    "pkg/service/aerospike" \
    "backupgo_mockgen.go" \
    "InfoGetter,AerospikeClient"

generate_external_mocks \
    "github.com/aerospike/backup-go" \
    "pkg/service/backupexecutor" \
    "backupgo_mockgen.go" \
    "Writer"

generate_external_mocks \
    "github.com/aerospike/backup-go" \
    "pkg/service/restoreexecutor" \
    "backupgo_mockgen.go" \
    "StreamingReader"

generate_mocks \
    "internal/server/handlers" \
    "configRetriever,manager,configApplier"

generate_mocks \
    "internal/server/configuration" \
    "storageReaderWriter"

echo "All mocks generated successfully."
